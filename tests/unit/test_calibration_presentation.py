import cv2
import numpy as np

from robotops.calibration.configuration import charuco_board, default_board
from robotops.calibration.contracts import ReferenceValidation
from robotops.calibration.presentation import reference_geometry
from robotops.calibration.visualization import printed_markers


def test_presented_marker_runs_match_actual_rgb_renderer_dictionary_and_metric_positions():
    board = default_board()
    bitmap = charuco_board(board).generateImage((1400, 1000), marginSize=0)
    patches = printed_markers(board.model_dump_json())
    assert {int(name.split("-")[1]) for name, _, _ in patches} == set(range(17))
    assert len(patches) < 350
    for name, center, size in patches:
        x = round(center[0] / board.measured_dimensions_m[0] * 1400)
        y = round(center[1] / board.measured_dimensions_m[1] * 1000)
        assert bitmap[y, x] == 0, name
        assert 0 < size[0] <= board.marker_length_m and size[1] > 0
    # Decode a complete projected pattern generated by the same physical board.
    ids = cv2.aruco.ArucoDetector(
        cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_100)
    ).detectMarkers(bitmap)[1]
    assert ids is not None and len(ids) == 17


def test_reference_overlay_uses_unscaled_saved_errors_and_handles_exact_zero():
    rows = (
        ReferenceValidation(
            reference_id="ref-1",
            expected_base_m=(0.1, 0.2, 0.3),
            predicted_base_m=(0.11, 0.2, 0.3),
            error_vector_m=(0.01, 0, 0),
            error_mm=10,
        ),
        ReferenceValidation(
            reference_id="ref-2",
            expected_base_m=(0, 0, 0.4),
            predicted_base_m=(0, 0, 0.4),
            error_vector_m=(0, 0, 0),
            error_mm=0,
        ),
    )
    evidence = reference_geometry(rows, "report-1")
    error = next(item for item in evidence.objects if item.name == "Inspection/reference-error-0")
    np.testing.assert_allclose(error.position, (0.105, 0.2, 0.3), atol=1e-12)
    assert abs(error.size[2] - 0.01) < 1e-12
    assert not any(item.name == "Inspection/reference-error-1" for item in evidence.objects)
    assert evidence.numbers["references"][1]["error_mm"] == 0
    camera = evidence.viewing_cameras[0]
    assert camera.role == "PRESENTATION" and camera.sensor_id is None
    assert np.linalg.norm(np.array(camera.position) - camera.target) < 1
    # Viewing geometry can change; recorded errors and point coordinates cannot.
    assert evidence.numbers["references"][0]["error_vector_m"] == [0.01, 0, 0]
